###############################################
#
# We use this file to store the possible combinations of file access to file when we are using open() function
#
############################################### 

###############################################
#
# Text Modes
#
# Returns and accepts Strings used text, csv and code files
#
###############################################	

# r   	: Open for reading only.
# 
# r+	: Open for reading AND writing.
# 
# a	    : Open for appending (writing at the end of the file).
# 
# a+  	: Open for appending AND reading.

###############################################
#
# Binary Modes
# 
# Returns and accepts raw Bytes used image, audio and extracts raw 1s and 0s
#
###############################################	

# rb      		: Open for reading binary data.
# 
# rb+ (or r+b)	: Open for reading AND writing binary data.
# 
# ab		    : Open for appending binary data.
# 
# ab+ (or a+b)	: Open for appending AND reading binary data.
