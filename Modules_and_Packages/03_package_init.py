# Packages and __init__.py
# A package is simply a directory containing multiple Python modules.
# To make Python treat the directory as a package, it MUST contain an __init__.py file.
print("To create a package:")
print("1. Create a folder (e.g., 'my_package')")
print("2. Add an empty file named '__init__.py' inside it.")
print("3. Add your module scripts (e.g., 'module1.py').")
print("4. Call it using: from my_package import module1")
